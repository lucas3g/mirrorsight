import type { Confidence, CraftBlock, Grade, InconclusiveReason, ModStatus } from '$lib/types';
import { defineMessages } from '../core.svelte';

type StatusKind = ModStatus['kind'];

/** Avaliação de itens: upgrade (para a build) e qualidade (comercial). */
interface EvaluationMessages {
  // ---------- Upgrade ----------
  /** Título do bloco: "Para a build X" ou "pesos genéricos". */
  buildFor: (build: string | null) => string;
  worseThan: string;
  betterThan: string;
  /** Veredito IGUAL por mods/rolls idênticos. */
  sameRolls: string;
  /** Veredito IGUAL com mods diferentes que se anulam (ex.: "all res" × três resistências). */
  equivalentText: string;
  sameNote: string;
  /** Pontas da régua (centro = seu item). */
  scale: { worse: string; yours: string; better: string };
  colChange: string;
  colYoursTheirs: string;
  colValue: string;
  /** Legenda de como ler os %. */
  how: string;
  confidenceShort: Record<Confidence, string>;
  noDifferences: string;
  /** Resistência abaixo do cap depois da troca. */
  resShort: (element: string, after: number) => string;
  /** A troca tira a resistência de baixo do cap. */
  resFixed: (element: string) => string;
  attrShort: (attr: string, missing: number) => string;
  attrFixed: (attr: string) => string;
  elements: Record<'fire' | 'cold' | 'lightning' | 'chaos', string>;
  attributes: Record<'str' | 'dex' | 'int', string>;

  // ---------- Qualidade ----------
  quality: string;
  qualityTitle: string;
  grade: Record<Grade, string>;
  inconclusive: string;
  confidence: Record<Confidence, string>;
  /** Coluna de status (mods que variam mostram o % do roll no lugar). */
  status: Record<StatusKind, string>;
  /** Legenda no fim da lista de mods (só os tipos presentes). */
  legend: Record<'roll' | 'db' | 'fixed' | 'variant' | 'mutated' | 'inconclusive', string>;
  reason: Record<InconclusiveReason, string>;
  openPrefixes: (n: number) => string;
  openSuffixes: (n: number) => string;
  craftedReplaceable: (n: number) => string;
  fracturedHigh: string;
  ilvlTop: string;
  ilvlLow: string;
  blocked: Record<CraftBlock, string>;
  uniqueVersion: (version: string, legacy: boolean) => string;
  uniqueCurrent: string;
  uniqueVariant: (variant: string) => string;
  uniqueRolls: (variable: number, fixed: number) => string;
  links: (links: number, max: number) => string;

  // ---------- Seu item / build ----------
  genericWeights: string;
  buildTitle: string;
  dataSource: (source: string) => string;
}

